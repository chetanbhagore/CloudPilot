"""Dockerfile and Container Specification Synthesizer.

Generates production-grade, multi-stage, security-hardened Dockerfiles
tailored to the detected framework and runtime requirements.
"""

from __future__ import annotations

from typing import Dict, Optional
from .repo_scanner import FrameworkType, ScanResult


class DockerfileSynthesizer:
    """Synthesizes secure, non-root, multi-stage Dockerfiles based on framework analysis."""

    @classmethod
    def generate(cls, scan_result: ScanResult, custom_port: Optional[int] = None) -> str:
        framework = scan_result.framework
        port = custom_port or scan_result.default_port or 8080
        is_worker = scan_result.is_worker

        if is_worker:
            return cls._worker_dockerfile(scan_result)

        if framework == FrameworkType.FASTAPI:
            return cls._fastapi_dockerfile(scan_result, port)
        elif framework == FrameworkType.STREAMLIT:
            return cls._streamlit_dockerfile(scan_result, port)
        elif framework == FrameworkType.DJANGO:
            return cls._django_dockerfile(scan_result, port)
        elif framework == FrameworkType.FLASK:
            return cls._flask_dockerfile(scan_result, port)
        elif framework == FrameworkType.REACT_VITE:
            return cls._react_vite_dockerfile(scan_result, port)
        elif framework == FrameworkType.NEXTJS:
            return cls._nextjs_dockerfile(scan_result, port)
        elif framework == FrameworkType.EXPRESS:
            return cls._express_dockerfile(scan_result, port)
        elif framework == FrameworkType.GO:
            return cls._go_dockerfile(scan_result, port)
        else:
            return cls._generic_dockerfile(scan_result, port)

    @classmethod
    def _fastapi_dockerfile(cls, scan: ScanResult, port: int) -> str:
        entrypoint = scan.entrypoint or "app.main:app"
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (FastAPI)
FROM python:3.11-slim AS builder

WORKDIR /app
ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1

RUN apt-get update && apt-get install -y --no-install-recommends gcc build-essential \\
    && rm -rf /var/lib/apt/lists/*

COPY requirements*.txt ./
RUN pip install --no-cache-dir --upgrade pip \\
    && pip install --no-cache-dir -r requirements.txt

# Final Runtime Stage
FROM python:3.11-slim

WORKDIR /app
ENV PORT={port} \\
    PYTHONUNBUFFERED=1

# Security: Non-root execution
RUN groupadd -r appuser && useradd -r -g appuser appuser

COPY --from=builder /usr/local/lib/python3.11/site-packages /usr/local/lib/python3.11/site-packages
COPY --from=builder /usr/local/bin /usr/local/bin
COPY . /app

RUN chown -R appuser:appuser /app
USER appuser

EXPOSE {port}

HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
    CMD python -c "import os, urllib.request; urllib.request.urlopen('http://localhost:' + str(os.getenv('PORT', '{port}')) + '/health')" || exit 1

CMD ["sh", "-c", "uvicorn {entrypoint} --host 0.0.0.0 --port ${{PORT:-{port}}} --workers 2"]
"""

    @classmethod
    def _streamlit_dockerfile(cls, scan: ScanResult, port: int) -> str:
        entrypoint = scan.entrypoint or "app.py"
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Streamlit)
FROM python:3.11-slim AS builder

WORKDIR /app
COPY requirements*.txt ./
RUN pip install --no-cache-dir --upgrade pip \\
    && pip install --no-cache-dir -r requirements.txt

FROM python:3.11-slim
WORKDIR /app
ENV PORT={port} \\
    STREAMLIT_SERVER_HEADLESS=true \\
    STREAMLIT_SERVER_ENABLE_CORS=false

RUN groupadd -r appuser && useradd -r -g appuser appuser
COPY --from=builder /usr/local/lib/python3.11/site-packages /usr/local/lib/python3.11/site-packages
COPY --from=builder /usr/local/bin /usr/local/bin
COPY . /app
RUN chown -R appuser:appuser /app
USER appuser

EXPOSE {port}

HEALTHCHECK --interval=30s --timeout=5s --start-period=10s --retries=3 \\
    CMD python -c "import os, urllib.request; urllib.request.urlopen('http://localhost:' + str(os.getenv('PORT', '{port}')) + '/_stcore/health')" || exit 1

CMD ["sh", "-c", "streamlit run {entrypoint} --server.port ${{PORT:-{port}}} --server.address 0.0.0.0"]
"""

    @classmethod
    def _django_dockerfile(cls, scan: ScanResult, port: int) -> str:
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Django)
FROM python:3.11-slim AS builder

WORKDIR /app
COPY requirements*.txt ./
RUN pip install --no-cache-dir --upgrade pip \\
    && pip install --no-cache-dir -r requirements.txt gunicorn

FROM python:3.11-slim
WORKDIR /app
ENV PORT={port} PYTHONUNBUFFERED=1

RUN groupadd -r appuser && useradd -r -g appuser appuser
COPY --from=builder /usr/local/lib/python3.11/site-packages /usr/local/lib/python3.11/site-packages
COPY --from=builder /usr/local/bin /usr/local/bin
COPY . /app
RUN chown -R appuser:appuser /app
USER appuser

EXPOSE {port}
CMD ["sh", "-c", "gunicorn --bind 0.0.0.0:${{PORT:-{port}}} --workers 2 wsgi:application"]
"""

    @classmethod
    def _flask_dockerfile(cls, scan: ScanResult, port: int) -> str:
        entrypoint = scan.entrypoint or "app:app"
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Flask)
FROM python:3.11-slim AS builder

WORKDIR /app
COPY requirements*.txt ./
RUN pip install --no-cache-dir --upgrade pip \\
    && pip install --no-cache-dir -r requirements.txt gunicorn

FROM python:3.11-slim
WORKDIR /app
ENV PORT={port} PYTHONUNBUFFERED=1

RUN groupadd -r appuser && useradd -r -g appuser appuser
COPY --from=builder /usr/local/lib/python3.11/site-packages /usr/local/lib/python3.11/site-packages
COPY --from=builder /usr/local/bin /usr/local/bin
COPY . /app
RUN chown -R appuser:appuser /app
USER appuser

EXPOSE {port}
CMD ["sh", "-c", "gunicorn --bind 0.0.0.0:${{PORT:-{port}}} --workers 2 {entrypoint}"]
"""

    @classmethod
    def _react_vite_dockerfile(cls, scan: ScanResult, port: int) -> str:
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (React/Vite SPA)
FROM node:20-alpine AS builder

WORKDIR /app
COPY package*.json ./
RUN npm ci

COPY . .
RUN npm run build

# Final Stage: Production NGINX web server
FROM nginx:alpine-slim

COPY --from=builder /app/dist /usr/share/nginx/html
# SPA Routing configuration
RUN echo 'server {{ listen {port}; location / {{ root /usr/share/nginx/html; index index.html; try_files $$uri $$uri/ /index.html; }} }}' > /etc/nginx/conf.d/default.conf

EXPOSE {port}
HEALTHCHECK --interval=30s --timeout=3s CMD wget -q --spider http://localhost:{port}/ || exit 1
CMD ["nginx", "-g", "daemon off;"]
"""

    @classmethod
    def _nextjs_dockerfile(cls, scan: ScanResult, port: int) -> str:
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Next.js)
FROM node:20-alpine AS deps
WORKDIR /app
COPY package*.json ./
RUN npm ci

FROM node:20-alpine AS builder
WORKDIR /app
COPY --from=deps /app/node_modules ./node_modules
COPY . .
RUN npm run build

FROM node:20-alpine AS runner
WORKDIR /app
ENV NODE_ENV=production PORT={port}

RUN addgroup --system --gid 1001 nodejs && adduser --system --uid 1001 nextjs
COPY --from=builder /app/public ./public
COPY --from=builder --chown=nextjs:nodejs /app/.next ./.next
COPY --from=builder /app/node_modules ./node_modules
COPY --from=builder /app/package.json ./package.json

USER nextjs
EXPOSE {port}
CMD ["sh", "-c", "npm start -- -p ${{PORT:-{port}}}"]
"""

    @classmethod
    def _express_dockerfile(cls, scan: ScanResult, port: int) -> str:
        entrypoint = scan.entrypoint or "node index.js"
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Express/Node)
FROM node:20-alpine AS builder
WORKDIR /app
COPY package*.json ./
RUN npm ci

COPY . .

FROM node:20-alpine
WORKDIR /app
ENV NODE_ENV=production PORT={port}

RUN addgroup -S appgroup && adduser -S appuser -G appgroup
COPY --from=builder /app /app
USER appuser

EXPOSE {port}
CMD ["sh", "-c", "{entrypoint}"]
"""

    @classmethod
    def _go_dockerfile(cls, scan: ScanResult, port: int) -> str:
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Go)
FROM golang:1.22-alpine AS builder
WORKDIR /app
COPY go.* ./
RUN go mod download
COPY . .
RUN CGO_ENABLED=0 GOOS=linux go build -ldflags="-w -s" -o /app/server .

FROM alpine:3.19
WORKDIR /app
ENV PORT={port}
RUN addgroup -S appgroup && adduser -S appuser -G appgroup
COPY --from=builder /app/server /app/server
USER appuser

EXPOSE {port}
CMD ["/app/server"]
"""

    @classmethod
    def _worker_dockerfile(cls, scan: ScanResult) -> str:
        entrypoint = scan.entrypoint or "python worker.py"
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Non-Web Worker)
FROM python:3.11-slim AS builder
WORKDIR /app
COPY requirements*.txt ./
RUN pip install --no-cache-dir --upgrade pip \\
    && pip install --no-cache-dir -r requirements.txt

FROM python:3.11-slim
WORKDIR /app
ENV PYTHONUNBUFFERED=1

RUN groupadd -r appuser && useradd -r -g appuser appuser
COPY --from=builder /usr/local/lib/python3.11/site-packages /usr/local/lib/python3.11/site-packages
COPY --from=builder /usr/local/bin /usr/local/bin
COPY . /app
RUN chown -R appuser:appuser /app
USER appuser

# Notice: Non-web worker does not expose ports
CMD ["sh", "-c", "{entrypoint}"]
"""

    @classmethod
    def _generic_dockerfile(cls, scan: ScanResult, port: int) -> str:
        return f"""# syntax=docker/dockerfile:1
# Generated by CloudPilot Workload Synthesizer (Generic Workload)
FROM alpine:3.19
WORKDIR /app
ENV PORT={port}
COPY . /app
EXPOSE {port}
CMD ["sh"]
"""

    @classmethod
    def generate_compose(cls, app_name: str, scan_result: ScanResult, host_port: int) -> str:
        container_port = scan_result.default_port or 8080
        is_worker = scan_result.is_worker

        ports_block = f"""    ports:
      - "{host_port}:{container_port}"
""" if not is_worker else ""

        return f"""version: '3.8'

services:
  {app_name}:
    build:
      context: .
      dockerfile: Dockerfile
    container_name: cloudpilot_{app_name}
    restart: unless-stopped
{ports_block}    environment:
      - PORT={container_port}
      - CLOUDPILOT_MANAGED=true
    labels:
      - "cloudpilot.app={app_name}"
      - "cloudpilot.managed=true"
"""
